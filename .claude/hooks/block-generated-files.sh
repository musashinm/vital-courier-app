#!/bin/sh
# PreToolUse (Edit|Write): blocks edits to files that a tool owns and would overwrite.
set -eu
file_path=$(jq -r '.tool_input.file_path // empty')
case "$file_path" in
  *.xcodeproj|*.xcodeproj/*)
    echo "Blocked: $file_path is generated by XcodeGen and overwritten on the next scripts/generate-project.sh run. Edit project.yml instead." >&2
    exit 2
    ;;
  */Package.resolved)
    echo "Blocked: Package.resolved is written by SwiftPM. Change the dependency in VitalCourierCore/Package.swift, then run 'swift package resolve --package-path VitalCourierCore' (or 'swift package update --package-path VitalCourierCore <name>')." >&2
    exit 2
    ;;
esac
